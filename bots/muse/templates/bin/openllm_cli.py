#!/usr/bin/env python3
"""Template CLI for the emulated OpenLLM connector.

Wraps an OpenAI-compatible gateway (openllm.sh) with stdlib only.

Auth: prefer the helper generated by
`scaffold-connector-skill --provider openllm` (see docs/03-credential-setup.md).
OPENLLM_API_KEY is local-test only (OPENLLM_LOCAL_TEST=1 or --local-test).
Never print or log the key.

Usage:
    openllm_cli.py chat --model <id-or-chain> --message "hello"
    openllm_cli.py models
    openllm_cli.py usage
"""

import argparse
import json
import os
import sys
import time
import urllib.error
import urllib.parse
import urllib.request


# FILL: GET path for spend/cap on the gateway (06-monitoring.md only names
# "the gateway's usage endpoint"). Dashboard-provided path wins when known.
# Override with --usage-path or OPENLLM_USAGE_PATH.
DEFAULT_USAGE_PATH = "/usage"

# Stable usage keys we print when present (else raw JSON). FILL if the
# gateway uses different names.
USAGE_SPEND_KEYS = ("spend",)
USAGE_CAP_KEYS = ("cap",)
USAGE_RESET_KEYS = ("reset_period", "reset", "period")

# FILL: production copies api_hosts from credentials.request_api_access
# (bare hostnames, e.g. ["api.openllm.sh"]). Empty = unset (no extra host
# filter). OPENLLM_API_HOSTS (comma-separated) is merged when set.
ALLOWED_API_HOSTS = []  # FILL


def _headers(api_key):
    return {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json",
    }


def _is_local_test(args):
    return bool(getattr(args, "local_test", False)) or os.environ.get(
        "OPENLLM_LOCAL_TEST"
    ) == "1"


def _allowed_hosts():
    hosts = [h.strip().lower() for h in ALLOWED_API_HOSTS if str(h).strip()]
    extra = os.environ.get("OPENLLM_API_HOSTS", "")
    hosts.extend(h.strip().lower() for h in extra.split(",") if h.strip())
    return hosts


def _validate_base_url(base_url, local_test):
    """Reject non-HTTPS (and hosts off the allowlist) before the bearer is sent."""
    parsed = urllib.parse.urlparse(base_url)
    host = (parsed.hostname or "").lower()
    scheme = (parsed.scheme or "").lower()
    if not scheme or not host:
        print("Invalid --base-url / OPENLLM_BASE_URL.", file=sys.stderr)
        sys.exit(2)
    http_loopback = scheme == "http" and host in ("127.0.0.1", "localhost")
    if scheme == "https":
        pass
    elif local_test and http_loopback:
        pass
    else:
        print(
            "Base URL must be https:// "
            "(http://127.0.0.1 or http://localhost only with "
            "--local-test / OPENLLM_LOCAL_TEST=1).",
            file=sys.stderr,
        )
        sys.exit(2)
    allowed = _allowed_hosts()
    if allowed and host not in allowed:
        print(
            "Host %r is not in the allowed API hosts list "
            "(FILL ALLOWED_API_HOSTS from credentials.request_api_access "
            "api_hosts, or set OPENLLM_API_HOSTS)."
            % (host,),
            file=sys.stderr,
        )
        sys.exit(2)


def _bearer_from_generated_helper():
    """Return (token, helper_loaded).

    FILL: after `/opt/hatch/skills/skill-creator/bin/scaffold-connector-skill
    --provider openllm`, copy the generated import from SKILL.md Auth.
    Expected function: get_bearer_token() -> str (confirm the name against
    the scaffold output; do not guess a different SDK).
    """
    try:
        # FILL: generated helper module + function from SKILL.md Auth.
        from openllm_auth import get_bearer_token
    except ImportError:
        return None, False
    return get_bearer_token(), True


def _resolve_api_key(local_test):
    token, helper_loaded = _bearer_from_generated_helper()
    if token:
        return token
    if local_test:
        token = os.environ.get("OPENLLM_API_KEY")
        if token:
            return token
        print(
            "Local-test mode is on but OPENLLM_API_KEY is not set. "
            "The key is never printed.",
            file=sys.stderr,
        )
        sys.exit(2)
    if helper_loaded:
        print(
            "Auth helper returned no token. See "
            "bots/muse/docs/03-credential-setup.md.",
            file=sys.stderr,
        )
        sys.exit(2)
    print(
        "No generated auth helper and not in local-test mode.\n"
        "Production: run scaffold-connector-skill --provider openllm "
        "(bots/muse/docs/03-credential-setup.md) and FILL the helper import "
        "in this CLI from the generated SKILL.md Auth section.\n"
        "Local testing: pass --local-test or set OPENLLM_LOCAL_TEST=1, and "
        "set OPENLLM_API_KEY.",
        file=sys.stderr,
    )
    sys.exit(2)


def _load_json_response(resp):
    return json.load(resp)


def _http_error_exit(err):
    body = err.read().decode(errors="replace")[:500]
    print("HTTP %s: %s" % (err.code, body), file=sys.stderr)
    sys.exit(2)


def _post(base_url, api_key, path, payload, timeout=120):
    req = urllib.request.Request(
        base_url.rstrip("/") + path,
        data=json.dumps(payload).encode(),
        headers=_headers(api_key),
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return _load_json_response(resp)
    except urllib.error.HTTPError as e:
        _http_error_exit(e)
    except urllib.error.URLError as e:
        print("Request failed: %s" % e.reason, file=sys.stderr)
        sys.exit(2)


def _get(base_url, api_key, path, timeout=30):
    req = urllib.request.Request(
        base_url.rstrip("/") + path, headers=_headers(api_key), method="GET"
    )
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return _load_json_response(resp)
    except urllib.error.HTTPError as e:
        _http_error_exit(e)
    except urllib.error.URLError as e:
        print("Request failed: %s" % e.reason, file=sys.stderr)
        sys.exit(2)


def _first_key(data, names):
    if not isinstance(data, dict):
        return None
    for name in names:
        if name in data:
            return data[name]
    return None


def cmd_chat(args, base_url, api_key):
    payload = {
        "model": args.model,
        "messages": [],
    }
    if args.system:
        payload["messages"].append({"role": "system", "content": args.system})
    payload["messages"].append({"role": "user", "content": args.message})
    if args.max_tokens:
        payload["max_tokens"] = args.max_tokens
    if args.temperature is not None:
        payload["temperature"] = args.temperature

    started = time.monotonic()
    data = _post(base_url, api_key, "/chat/completions", payload)
    latency_ms = int(round((time.monotonic() - started) * 1000))
    choice = data["choices"][0]["message"]["content"]
    usage = data.get("usage", {})
    print(choice)
    print("---")
    print(json.dumps({
        "model_served": data.get("model"),
        "prompt_tokens": usage.get("prompt_tokens"),
        "completion_tokens": usage.get("completion_tokens"),
        "total_tokens": usage.get("total_tokens"),
        "latency_ms": latency_ms,
    }))


def cmd_models(args, base_url, api_key):
    data = _get(base_url, api_key, "/models")
    for m in data.get("data", []):
        print(m.get("id"))


def cmd_usage(args, base_url, api_key):
    path = args.usage_path or os.environ.get("OPENLLM_USAGE_PATH") or DEFAULT_USAGE_PATH
    if not path.startswith("/"):
        path = "/" + path
    data = _get(base_url, api_key, path)
    spend = _first_key(data, USAGE_SPEND_KEYS)
    cap = _first_key(data, USAGE_CAP_KEYS)
    reset_period = _first_key(data, USAGE_RESET_KEYS)
    if spend is not None or cap is not None or reset_period is not None:
        print(json.dumps({
            "spend": spend,
            "cap": cap,
            "reset_period": reset_period,
        }))
        return
    print(json.dumps(data))


def main():
    p = argparse.ArgumentParser(description="OpenLLM gateway CLI (template)")
    p.add_argument("--base-url", default=os.environ.get("OPENLLM_BASE_URL"),
                   help="Gateway base URL (from the openllm.sh dashboard)")
    p.add_argument(
        "--local-test",
        action="store_true",
        help="Allow OPENLLM_API_KEY and http://127.0.0.1|localhost "
             "(also OPENLLM_LOCAL_TEST=1)",
    )
    sub = p.add_subparsers(dest="cmd", required=True)

    c = sub.add_parser("chat", help="Run a chat completion")
    c.add_argument("--model", required=True, help="Model id or chain name")
    c.add_argument("--message", required=True, help="User message")
    c.add_argument("--system", default=None, help="System prompt")
    c.add_argument("--max-tokens", type=int, default=None)
    c.add_argument("--temperature", type=float, default=None)

    sub.add_parser("models", help="List available models/chains")

    u = sub.add_parser("usage", help="GET gateway usage/spend for the scoped key")
    u.add_argument(
        "--usage-path",
        default=None,
        help="FILL usage path (default %s or OPENLLM_USAGE_PATH)"
             % DEFAULT_USAGE_PATH,
    )

    args = p.parse_args()
    if not args.base_url:
        print("Set --base-url or OPENLLM_BASE_URL (from the dashboard).",
              file=sys.stderr)
        sys.exit(2)

    local_test = _is_local_test(args)
    _validate_base_url(args.base_url, local_test)
    api_key = _resolve_api_key(local_test)

    if args.cmd == "chat":
        cmd_chat(args, args.base_url, api_key)
    elif args.cmd == "models":
        cmd_models(args, args.base_url, api_key)
    elif args.cmd == "usage":
        cmd_usage(args, args.base_url, api_key)


if __name__ == "__main__":
    main()
